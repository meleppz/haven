// Regenerates src/lib/art.ts from the Figma SVG exports in assets/mascot/mascot-*.svg and assets/icons/feature-*.svg.
//   npm run gen:art
//
// Why this exists: Figma frames carry a solid #1E1E1E fill, which the SVG export includes as the FIRST <rect>. PNG export
// bakes that dark rectangle into the image. We export SVG, strip that rectangle here, and render with react-native-svg.
// Exports taken from inside a screen can also carry that screen's page-color rectangle (393x852); it is stripped too.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../assets", import.meta.url));
const out = fileURLToPath(new URL("../src/lib/art.ts", import.meta.url));

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function load(dir, prefix) {
  return readdirSync(join(root, dir))
    .filter((f) => f.startsWith(prefix) && f.endsWith(".svg"))
    .sort()
    .map((f) => {
      let svg = readFileSync(join(root, dir, f), "utf8").trim();
      const before = svg.length;
      svg = svg.replace(/<rect[^>]*fill="#1E1E1E"[^>]*\/>\s*/i, "");
      if (svg.length === before) throw new Error(`background rect (#1E1E1E) not found in ${f}: export the node as SVG from Figma`);
      svg = svg.replace(/<rect[^>]*height="852"[^>]*\/>\s*/, "");
      const m = svg.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
      let name = camel(f.replace(prefix, "").replace(".svg", ""));
      if (name === "247") name = "ahli247"; // "feature-24-7.svg" -> a valid identifier
      return { name, svg, w: Number(m[1]), h: Number(m[2]) };
    });
}

const mascots = load("mascot", "mascot-");
const features = load("icons", "feature-");

const block = (title, items) =>
  `export const ${title} = {\n` + items.map((i) => `  ${i.name}: { xml: ${JSON.stringify(i.svg)}, width: ${i.w}, height: ${i.h} },`).join("\n") + "\n} as const;\n";

writeFileSync(
  out,
  "// GENERATED by scripts/gen-art.mjs from assets/mascot/*.svg and assets/icons/feature-*.svg (Figma exports, frame background removed).\n" +
    "// Use the <Mascot /> and <FeatureIcon /> components instead of importing this directly.\n\n" +
    block("mascotArt", mascots) +
    "\n" +
    block("featureArt", features) +
    "\nexport type MascotName = keyof typeof mascotArt;\nexport type FeatureIconName = keyof typeof featureArt;\n",
);
console.log("mascots:", mascots.map((m) => m.name).join(", "));
console.log("features:", features.map((m) => m.name).join(", "));
