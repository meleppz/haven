// Regenerates src/lib/ui-icons.ts from the SVG icons in assets/icons/ui/*.svg (Figma exports).
//   npm run gen:icons
// Colors are baked into the Figma SVGs (e.g. home-bold is yellow, home-linear is grey), so each state is its own file.
// Render with <SvgXml xml={uiIcons.homeBold} width={24} height={24} />.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../assets/icons/ui", import.meta.url));
const out = fileURLToPath(new URL("../src/lib/ui-icons.ts", import.meta.url));

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const entries = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    let svg = readFileSync(join(dir, f), "utf8").trim();
    // react-native-svg's parser does not need these web-only attributes.
    svg = svg.replace(/\s+style="[^"]*"/, "").replace(/\s+preserveAspectRatio="[^"]*"/, "").replace(/\s+overflow="[^"]*"/, "");
    return `  ${camel(f.replace(".svg", ""))}: ${JSON.stringify(svg)},`;
  });

writeFileSync(
  out,
  "// GENERATED by scripts/gen-icons.mjs from assets/icons/ui/*.svg (exported from Figma). Colors are baked into the SVGs.\n" +
    "// Render with <SvgXml xml={uiIcons.homeBold} width={24} height={24} />.\n\n" +
    "export const uiIcons = {\n" +
    entries.join("\n") +
    "\n} as const;\n\nexport type UiIconName = keyof typeof uiIcons;\n",
);
console.log("wrote", entries.length, "icons");
